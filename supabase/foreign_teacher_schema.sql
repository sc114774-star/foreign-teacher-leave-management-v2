create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.foreign_teacher_profiles(user_id, name, email, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', new.email), new.email,
    case when new.raw_app_meta_data->>'role' in ('teacher','cingshan','dongyuan','admin')
      then (new.raw_app_meta_data->>'role')::public.foreign_teacher_app_role else 'teacher'::public.foreign_teacher_app_role end)
  on conflict (user_id) do update set email = excluded.email, name = excluded.name;
  return new;
end;
$$;

create trigger foreign_teacher_on_auth_user_created
after insert on auth.users for each row execute procedure public.handle_new_user();

