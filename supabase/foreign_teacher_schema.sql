create or replace function public.foreign_teacher_current_role()
returns public.foreign_teacher_app_role language sql stable security definer set search_path = public as $$
  select coalesce((select role from public.foreign_teacher_profiles where user_id = auth.uid()), 'teacher'::public.foreign_teacher_app_role);
$$;

create or replace function public.foreign_teacher_can_access_application(application_id_input bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.foreign_teacher_leave_applications a
    where a.id = application_id_input
      and (a.teacher_id = auth.uid() or public.foreign_teacher_current_role() in ('cingshan','dongyuan','admin'))
  );
$$;

create or replace function public.foreign_teacher_can_review_school(school_input text)
returns boolean language sql stable security definer set search_path = public as $$
  select public.foreign_teacher_current_role() = 'admin'
    or (public.foreign_teacher_current_role() = 'cingshan' and school_input = '青山國小')
    or (public.foreign_teacher_current_role() = 'dongyuan' and school_input = '東原國中');
$$;

